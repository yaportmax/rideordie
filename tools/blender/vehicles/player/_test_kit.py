import sys, os, math, time
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from post import *
t0=time.time()
new_scene()
p = Part("body")
p.box('metal_dark', (0,0,0.5), (1.0,2.0,0.4), bev=0.02)
p.cyl('chrome' if False else 'chrome', (0,1.0,0.9), 0.15, 0.5, axis='f', n=16, bev=0.01)
p.cyl('rubber', (0.5,0.5,1.2), 0.1, 0.3, axis='z', n=12, r2=0.03)
p.sph('brass', (-0.5,0,1.0), 0.15)
p.torus('rim', (0.6,-0.5,0.8), 0.2, 0.03, axis='x')
p.tube('metal_bare', [(-0.6,-1,0.3),(-0.6,-1,1.2),(-0.2,-1,1.4),(0.4,-1,1.4)], 0.03, rad=0.15)
# curved panel with hole and dents
def fn(u,v):
    return (u, v, 0.9 + 0.08*(1-(u/0.5)**2) )
poly = rrect_poly(-0.5,-0.7,0.5,0.7,0.1)
hole = [(0.2+0.08*math.cos(a*math.pi/8), 0.3+0.08*math.sin(a*math.pi/8)) for a in range(16)]
p.shell('paint', poly, fn, out=(0,0,1), thick=0.02, dens=0.05, holes=[hole], dent=[(-0.2,-0.2,0.12,0.015)])
p.loft('paint2', [[(-0.3+0.6*math.cos(a*math.pi/6)*(1+0.2*i),1.2+0.3*i,1.5+0.3*math.sin(a*math.pi/6)*(1+0.2*i)) for a in range(12)] for i in range(4)])
o = p.build()
socket("seat_driver",(0.3,0,1.0))
tw=time.time()
weighted_normals(o)
print("wn", time.time()-tw, len(o.data.polygons))
img = make_grunge("g_paint",1024,'paint',0.6,1)
hook_texture('paint', img); hook_texture('paint2', img)
box_uv(o, 0.6)
bake_ao([o], dist=0.8, samples=32)
shade_vcol([o], lambda ao,x,f,z,nx,nf,nz: 0.25+0.75*ao)
print("tris", mesh_stats([o]))
export("models/_test/kit.glb", [o] + vlib._SOCKETS)
print("done", time.time()-t0)
